// rota los strings base ('#' al inicio = MSB) → representación bit col0=LSB
for (const [c, rows] of Object.entries(defs)) {
  G[c] = rows.map(r => {
    let v = 0;
    for (let col = 0; col < 5; col++) if (r[col] === '#') v |= (1 << col);
    return v;
  });
}

// Acentos: base comprimida una fila + tilde/diéresis
function accent(base) {
  const g = base.slice();   // copia
  const shifted = new Array(7).fill(0);
  for (let r = 6; r > 0; r--) shifted[r] = g[r - 1];
  shifted[0] = 0b01010;
  return shifted;
}
function diaeresis(base) {
  const shifted = new Array(7).fill(0);
  for (let r = 6; r > 0; r--) shifted[r] = base[r - 1];
  shifted[0] = 0b10101;
  return shifted;
}
const accMap = { 'Á':'A','É':'E','Í':'I','Ó':'O','Ú':'U','Ñ':'N','á':'a','é':'e','í':'i','ó':'o','ú':'u','ñ':'n' };
for (const [c, base] of Object.entries(accMap)) G[c] = accent(G[base]);
G['Ü'] = diaeresis(G['U']);
G['ü'] = diaeresis(G['u']);

export const Font5x7 = {
  width: 5, height: 7, spacing: 1,
  has(c) { return c in G; },
  get(c) { return G[c] ?? null; },
  measureText(s) {
    let w = 0;
    for (const c of s) w += 6;
    return w > 0 ? w - 1 : 0;
  },
};