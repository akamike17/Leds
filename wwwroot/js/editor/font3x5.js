// Acentos (mismo patrón que C#: comprimir + tilde/diéresis arriba)
function accent(base) {
  const s = new Array(5).fill(0);
  for (let r = 4; r > 0; r--) s[r] = base[r - 1];
  s[0] = 0b010;
  return s;
}
function diaeresis(base) {
  const s = new Array(5).fill(0);
  for (let r = 4; r > 0; r--) s[r] = base[r - 1];
  s[0] = 0b101;
  return s;
}
