// Fuente 3x5 (compacta). Coincide EXACTO con Domain/Rendering/Font3x5.cs.
// Glifo = 5 filas de 3 bits (bit 0 = columna izquierda). PARIDAD C#↔JS obligatoria.
// Omitidos (no caben en 3 col): M, W, @, %, &, # → get() devuelve null.
const G = {};
function def(c, rows) {
  let g = [];
  for (let r = 0; r < 5; r++) {
    let v = 0;
    for (let col = 0; col < 3; col++) if (rows[r][col] === '#') v |= (1 << col);
    g.push(v);
  }
  G[c] = g;
}

