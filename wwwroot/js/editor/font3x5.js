if (G['U']) G['Ü'] = diaeresis(G['U']);

export const Font3x5 = {
  width: 3, height: 5, spacing: 1,
  has(c) { return c in G; },
  get(c) { return G[c] ?? null; },
  measureText(s) {
    let w = 0;
    for (const c of s) w += 4; // width(3) + spacing(1)
    return w > 0 ? w - 1 : 0;
  },
};